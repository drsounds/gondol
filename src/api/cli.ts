#!/usr/bin/env bun
// gondol-api: writes what a server needs to serve the apps' HTTP APIs into one folder, for the
// host's edge function to import (docs/guide/api.md):
//
//   <out>/openapi.json  every app's manifest `api`, merged (buildOpenApiDocument)
//   <out>/gateway.ts    the gateway (gateway.ts), copied as is: it imports nothing
//   <out>/apps.json     every app's `functions` and `mcp`, for the app router (buildAppRegistry)
//   <out>/router.ts     the app router (router.ts), copied as is: it imports only the gateway
//
//   bunx gondol-api --apps src/apps --builtin ai,oauth --out supabase/functions/_shared/gondol-api
//
// `--functions <dir>` also writes gondol's Supabase edge function for the router to
// <dir>/app-router/index.ts (from supabase/functions/app-router), importing the files above.
//
// `--check` writes nothing and fails when the files are out of date (for CI). `--title` and
// `--version` set the document's info.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { discoverApps } from "../vite/apps.mjs";
import { parseManifest } from "../apps/manifest";
import { buildOpenApiDocument, type ApiSource } from "./openapi";
import { buildAppRegistry, type FunctionSource } from "./functions";

function arg(name: string): string | undefined {
  const index = process.argv.indexOf(`--${name}`);
  return index === -1 ? undefined : process.argv[index + 1];
}

const appsDir = resolve(arg("apps") ?? "apps");
const out = resolve(arg("out") ?? "api");
const builtin = (arg("builtin") ?? "").split(",").map((id) => id.trim()).filter(Boolean);
const check = process.argv.includes("--check");

const functionsDir = arg("functions");
const manifests = discoverApps(appsDir, builtin).map((app: { dir: string }) => parseManifest(JSON.parse(readFileSync(join(app.dir, "manifest.json"), "utf8"))));
const sources: ApiSource[] = manifests.map((manifest) => ({ id: manifest.id, name: manifest.name, api: manifest.api }));
const document = buildOpenApiDocument(sources, { title: arg("title"), version: arg("version") });
const registry = buildAppRegistry(
  manifests.map((manifest): FunctionSource => ({ id: manifest.id, name: manifest.name, description: manifest.description, functions: manifest.functions, mcp: manifest.mcp, api: manifest.api })),
);

const here = dirname(fileURLToPath(import.meta.url));
const gateway = readFileSync(join(here, "gateway.ts"), "utf8");
const router = readFileSync(join(here, "router.ts"), "utf8");
const generated = (source: string) => `// Generated by gondol-api from gondol's ${source}: don't edit, change it in gondol.\n`;
const files: Record<string, string> = {
  [join(out, "openapi.json")]: `${JSON.stringify(document, null, 2)}\n`,
  [join(out, "gateway.ts")]: `${generated("src/api/gateway.ts")}${gateway}`,
  [join(out, "apps.json")]: `${JSON.stringify(registry, null, 2)}\n`,
  [join(out, "router.ts")]: `${generated("src/api/router.ts")}${router}`,
};
if (functionsDir) {
  const fn = readFileSync(join(here, "../../supabase/functions/app-router/index.ts"), "utf8");
  const target = join(resolve(functionsDir), "app-router");
  // The function imports ../_shared/gondol-api/…; point it at wherever --out is.
  const shared = relative(target, out).split("\\").join("/");
  files[join(target, "index.ts")] = `${generated("supabase/functions/app-router/index.ts")}${fn.replaceAll("../_shared/gondol-api/", `${shared}/`)}`;
}

let stale = false;
for (const [path, content] of Object.entries(files)) {
  const current = existsSync(path) ? readFileSync(path, "utf8") : null;
  if (current === content) continue;
  if (check) {
    console.error(`${relative(process.cwd(), path)} is out of date: run gondol-api.`);
    stale = true;
  } else {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, content);
    console.log(`wrote ${relative(process.cwd(), path)}`);
  }
}
const operations = Object.values(document.paths).reduce((sum, item) => sum + Object.keys(item).length, 0);
const tools = Object.values(registry.apps).reduce((sum, app) => sum + app.tools.length, 0);
const functions = Object.values(registry.apps).reduce((sum, app) => sum + Object.keys(app.functions).length, 0);
if (!check) console.log(`gondol-api: ${operations} operations, ${functions} functions and ${tools} MCP tools from ${manifests.length} apps`);
if (stale) process.exit(1);
