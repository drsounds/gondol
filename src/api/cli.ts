#!/usr/bin/env bun
// gondol-api: writes what a server needs to serve the apps' HTTP APIs into one folder, for the
// host's edge function to import (docs/guide/api.md):
//
//   <out>/openapi.json  every app's manifest `api`, merged (buildOpenApiDocument)
//   <out>/gateway.ts    the gateway (gateway.ts), copied as is: it imports nothing
//
//   bunx gondol-api --apps src/apps --builtin ai,oauth --out supabase/functions/_shared/gondol-api
//
// `--check` writes nothing and fails when the files are out of date (for CI). `--title` and
// `--version` set the document's info.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { discoverApps } from "../vite/apps.mjs";
import { parseManifest } from "../apps/manifest";
import { buildOpenApiDocument, type ApiSource } from "./openapi";

function arg(name: string): string | undefined {
  const index = process.argv.indexOf(`--${name}`);
  return index === -1 ? undefined : process.argv[index + 1];
}

const appsDir = resolve(arg("apps") ?? "apps");
const out = resolve(arg("out") ?? "api");
const builtin = (arg("builtin") ?? "").split(",").map((id) => id.trim()).filter(Boolean);
const check = process.argv.includes("--check");

const sources: ApiSource[] = discoverApps(appsDir, builtin).map((app: { dir: string }) => {
  const manifest = parseManifest(JSON.parse(readFileSync(join(app.dir, "manifest.json"), "utf8")));
  return { id: manifest.id, name: manifest.name, api: manifest.api };
});
const document = buildOpenApiDocument(sources, { title: arg("title"), version: arg("version") });

const here = dirname(fileURLToPath(import.meta.url));
const gateway = readFileSync(join(here, "gateway.ts"), "utf8");
const files: Record<string, string> = {
  "openapi.json": `${JSON.stringify(document, null, 2)}\n`,
  "gateway.ts": `// Generated by gondol-api from gondol's src/api/gateway.ts: don't edit, change it in gondol.\n${gateway}`,
};

let stale = false;
for (const [name, content] of Object.entries(files)) {
  const path = join(out, name);
  const current = existsSync(path) ? readFileSync(path, "utf8") : null;
  if (current === content) continue;
  if (check) {
    console.error(`${relative(process.cwd(), path)} is out of date: run gondol-api.`);
    stale = true;
  } else {
    mkdirSync(out, { recursive: true });
    writeFileSync(path, content);
    console.log(`wrote ${relative(process.cwd(), path)}`);
  }
}
const operations = Object.values(document.paths).reduce((sum, item) => sum + Object.keys(item).length, 0);
if (!check) console.log(`gondol-api: ${operations} operations from ${sources.filter((s) => s.api).length} apps`);
if (stale) process.exit(1);
